"""Build CSL character metadata; the installed engine cannot read raw XML at runtime."""
import argparse
import json
from pathlib import Path
import re
import struct
import time
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]


def parse_atlas(path, res):
    root = ET.parse(path).getroot()
    if root.tag != 'TextureAtlas':
        raise ValueError('Expected TextureAtlas root')
    texture = path.parent / root.get('imagePath', path.with_suffix('.png').name)
    texture = texture.resolve()
    asset = texture.relative_to(res.resolve()).as_posix()
    if not texture.is_file():
        raise ValueError(f'Missing texture: {texture}')
    data = texture.read_bytes()
    if data[:8] != b'\x89PNG\r\n\x1a\n':
        raise ValueError(f'Not a PNG texture: {texture}')
    width, height = struct.unpack('>II', data[16:24])
    groups = {}
    seen = set()
    for node in root.findall('SubTexture'):
        name = node.attrib['name']
        if not name or name in seen:
            raise ValueError(f'Empty or duplicate frame name: {name!r}')
        seen.add(name)
        if node.get('rotated', 'false').lower() not in ('false', '0'):
            raise ValueError(f'Rotated frames are unsupported: {name}')
        x, y, w, h = (int(node.attrib[k]) for k in ('x', 'y', 'width', 'height'))
        fx, fy = (int(node.get(k, '0')) for k in ('frameX', 'frameY'))
        fw, fh = int(node.get('frameWidth', w)), int(node.get('frameHeight', h))
        if min(x, y) < 0 or min(w, h, fw, fh) <= 0 or x+w > width or y+h > height:
            raise ValueError(f'Invalid or out-of-bounds frame: {name}')
        if fx > 0 or fy > 0 or -fx+w > fw or -fy+h > fh:
            raise ValueError(f'Invalid trimmed frame bounds: {name}')
        match = re.fullmatch(r'(.*?)([0-9]+)', name)
        animation = match[1] if match and match[1] else name
        number = int(match[2]) if match else 0
        groups.setdefault(animation, []).append((number, name, (x, y, w, h, fx, fy, fw, fh)))
    if not groups:
        raise ValueError('TextureAtlas contains no SubTexture frames')
    for animation, frames in groups.items():
        frames.sort(key=lambda f: (f[0], f[1]))
        print(f'[game_player] Animation {animation!r}: {len(frames)} frames')
    return asset, width, height, groups


def generate(res, output):
    folder = res / 'game_player'
    lines = ['// Generated by tools/import_game_player.py; do not edit.',
             'load_game_player_definition :: proc() -> Game_Player_Definition {',
             '    d := new(Game_Player_Definition);']
    # Prefer character.* then the existing player.*; a Spine always wins over XML.
    order = lambda p: (p.stem not in ('character', 'player'), p.stem != 'character', p.name)
    spines = sorted(folder.glob('*.spine'), key=order)
    xmls = sorted(folder.glob('*.xml'), key=order)
    if spines:
        asset = spines[0].relative_to(res).as_posix()
        print(f'[game_player] Using existing Spine: {asset}')
        lines += [f'    d.spine_path = {json.dumps(asset, ensure_ascii=False)};']
    elif xmls:
        asset, width, height, groups = parse_atlas(xmls[0], res)
        lines += [f'    d.texture_path = {json.dumps(asset, ensure_ascii=False)};',
                  f'    d.sheet_size = {{{width}, {height}}};']
        for index, (name, frames) in enumerate(groups.items()):
            # Split functions to avoid the CSL VM register limit on large atlases.
            lines += [f'    game_player_animation_{index}(d);']
        lines += ['    return d;', '}']
        for index, (name, frames) in enumerate(groups.items()):
            lines += [f'game_player_animation_{index} :: proc(d: Game_Player_Definition) {{',
                      '    a := new(Game_Player_Animation);',
                      f'    a.name = {json.dumps(name, ensure_ascii=False)};']
            for start in range(0, len(frames), 32):
                lines += [f'    game_player_frames_{index}_{start}(a);']
            lines += ['    d.animations.append(a);', '}']
            for start in range(0, len(frames), 32):
                lines += [f'game_player_frames_{index}_{start} :: proc(a: Game_Player_Animation) {{']
                for _, _, (x, y, w, h, fx, fy, fw, fh) in frames[start:start+32]:
                    lines += [f'    a.frames.append(Game_Player_Frame{{source={{{x},{y}}}, size={{{w},{h}}}, trim={{{fx},{fy}}}, canvas={{{fw},{fh}}}}});']
                lines += ['}']
    else:
        print('[game_player] No Spine or XML character found; using stock character')
    if not xmls or spines:
        lines += ['    return d;', '}']
    text = '\n'.join(lines) + '\n'
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text(encoding='utf-8') != text:
        output.write_text(text, encoding='utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--watch', action='store_true', help='Regenerate when game_player files change')
    args = parser.parse_args()
    last = None
    while True:
        files = ROOT / 'res' / 'game_player'
        snapshot = tuple((p.name, p.stat().st_mtime_ns, p.stat().st_size) for p in sorted(files.glob('*')) if p.is_file())
        if snapshot != last:
            try:
                generate(ROOT / 'res', ROOT / 'scripts' / 'rhythm' / 'game_player_generated.csl')
            except (ValueError, KeyError, OSError, ET.ParseError, struct.error) as error:
                print(f'[game_player] XML/import loading error: {error}', flush=True)
                if not args.watch:
                    return 1
            last = snapshot
        if not args.watch:
            return 0
        time.sleep(1)


if __name__ == '__main__':
    raise SystemExit(main())
